const MATERIAL_ICON_ALIASES = {
  "create_new_folder": "folder",
  "notes": "text_snippet",
  "preview": "visibility",
  "quiz": "assignment"
};

const MATERIAL_ICON_TEXT_SELECTOR = [
  ".dashboard-material-icon",
  ".cfg-material-icon",
  ".ttp-material-icon",
  ".tv-stepper-icon",
  ".ui-color-picker-trigger-icon",
  ".phono-material-icon",
  ".cj-material-icon",
  ".nc-material-icon"
].join(",");

let materialIconObserver = null;
let materialIconHydrationScheduled = false;

export function renderMaterialIcon(name, { className = "student-icon", id = "" } = {}) {
  const safeClassName = String(className || "").trim();
  const idAttr = String(id || "").trim() ? ` id="${escapeHtml(id)}"` : "";
  return `
    <span${idAttr} class="${escapeHtml(safeClassName)}" aria-hidden="true" data-material-icon-name="${escapeHtml(resolveMaterialIconName(name))}">
      ${renderMaterialIconSvg(name)}
    </span>
  `;
}

export function renderMaterialIconSvg(name) {
  const { definition, resolvedName } = getMaterialIconDefinition(name);
  const paths = definition.paths
    .map((path) => `<path d="${escapeHtml(path)}"></path>`)
    .join("");
  const transform = getMaterialIconCoordinateTransform(definition);
  const content = transform
    ? `<g transform="${escapeHtml(transform)}">${paths}</g>`
    : paths;

  return `
    <svg
      class="material-icon-svg"
      viewBox="${escapeHtml(definition.viewBox)}"
      focusable="false"
      aria-hidden="true"
      data-material-icon="${escapeHtml(resolvedName)}"
    >${content}</svg>
  `;
}

export function setMaterialIcon(element, name) {
  if (!element) return "";
  const resolvedName = resolveMaterialIconName(name);
  element.dataset.materialIconName = resolvedName;
  element.innerHTML = renderMaterialIconSvg(resolvedName);
  return resolvedName;
}

export function hydrateMaterialIcons(root = document) {
  if (!root) return;

  if (isMaterialIconElement(root)) {
    hydrateMaterialIconElement(root);
  }

  if (typeof root.querySelectorAll !== "function") return;
  root.querySelectorAll(MATERIAL_ICON_TEXT_SELECTOR).forEach(hydrateMaterialIconElement);
}

export function startMaterialIconHydration({ root = document } = {}) {
  hydrateMaterialIcons(root);

  if (materialIconObserver || !root || !root.body || typeof MutationObserver !== "function") {
    return materialIconObserver;
  }

  materialIconObserver = new MutationObserver((mutations) => {
    for (const mutation of mutations) {
      if (mutation.type === "characterData") {
        const parent = mutation.target?.parentElement;
        if (parent) scheduleMaterialIconHydration(parent);
        continue;
      }

      if (mutation.type !== "childList") continue;
      mutation.addedNodes.forEach((node) => {
        if (node.nodeType === Node.ELEMENT_NODE) {
          scheduleMaterialIconHydration(node);
        } else if (node.nodeType === Node.TEXT_NODE && node.parentElement) {
          scheduleMaterialIconHydration(node.parentElement);
        }
      });
    }
  });

  materialIconObserver.observe(root.body, {
    childList: true,
    characterData: true,
    subtree: true
  });

  return materialIconObserver;
}

function scheduleMaterialIconHydration(root) {
  if (!root) return;

  const run = () => hydrateMaterialIcons(root);
  if (materialIconHydrationScheduled) {
    requestAnimationFrame(run);
    return;
  }

  materialIconHydrationScheduled = true;
  requestAnimationFrame(() => {
    materialIconHydrationScheduled = false;
    run();
  });
}

function hydrateMaterialIconElement(element) {
  if (!isMaterialIconElement(element)) return false;

  const iconName = getIconNameFromElement(element);
  const resolvedName = getResolvableMaterialIconName(iconName);
  if (!resolvedName) return false;

  const currentSvg = element.querySelector(":scope > svg.material-icon-svg");
  if (currentSvg?.dataset?.materialIcon === resolvedName && element.childElementCount === 1) {
    element.dataset.materialIconName = resolvedName;
    return true;
  }

  return Boolean(setMaterialIcon(element, resolvedName));
}

function getIconNameFromElement(element) {
  const textName = Array.from(element.childNodes)
    .filter((node) => node.nodeType === Node.TEXT_NODE)
    .map((node) => node.textContent)
    .join("")
    .trim();
  const resolvedTextName = getResolvableMaterialIconName(textName);
  if (resolvedTextName) return resolvedTextName;

  const explicitName = String(element.dataset?.materialIconName || "").trim();
  const resolvedExplicitName = getResolvableMaterialIconName(explicitName);
  if (resolvedExplicitName) return resolvedExplicitName;

  const svgName = String(element.querySelector(":scope > svg.material-icon-svg")?.dataset?.materialIcon || "").trim();
  const resolvedSvgName = getResolvableMaterialIconName(svgName);
  if (resolvedSvgName) return resolvedSvgName;

  return textName;
}

function isMaterialIconElement(element) {
  return Boolean(
    element?.nodeType === Node.ELEMENT_NODE &&
    typeof element.matches === "function" &&
    element.matches(MATERIAL_ICON_TEXT_SELECTOR)
  );
}

function resolveMaterialIconName(name) {
  return getMaterialIconDefinition(name).resolvedName;
}

function getMaterialIconDefinition(name) {
  const safeName = String(name || "").trim();
  const resolvedName = getResolvableMaterialIconName(safeName) || "sync";
  return {
    definition: MATERIAL_ICON_DEFINITIONS[resolvedName],
    resolvedName
  };
}

function getResolvableMaterialIconName(name) {
  const safeName = String(name || "").trim();
  if (MATERIAL_ICON_DEFINITIONS[safeName]) return safeName;

  const alias = MATERIAL_ICON_ALIASES[safeName];
  if (alias && MATERIAL_ICON_DEFINITIONS[alias]) return alias;

  return "";
}

function getMaterialIconCoordinateTransform(definition = {}) {
  if (definition.transform) return definition.transform;
  if (definition.flipY === false) return "";

  const parts = String(definition.viewBox || "")
    .trim()
    .split(/\s+/)
    .map((part) => Number(part));
  const minY = Number.isFinite(parts[1]) ? parts[1] : 0;
  const height = Number.isFinite(parts[3]) ? parts[3] : 960;
  return `matrix(1 0 0 -1 0 ${formatSvgNumber((minY * 2) + height)})`;
}

function formatSvgNumber(value) {
  return Number.isInteger(value) ? String(value) : String(Number(value.toFixed(4)));
}

function escapeHtml(value) {
  return String(value ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}
